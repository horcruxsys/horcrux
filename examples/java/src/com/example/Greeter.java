package com.example;

/**
 * Greeter provides a simple greeting utility.
 */
public class Greeter {
    /**
     * Returns a greeting string for the given name.
     *
     * @param name the name to greet
     * @return greeting string
     */
    public String greet(final String name) {
        return "Hello, " + name + "!";
    }
}
